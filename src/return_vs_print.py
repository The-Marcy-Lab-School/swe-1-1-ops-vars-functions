def add(a, b):
    result = a + b
    print(f"The sum of {a} and {b} is {result}")


def subtract(a, b):
    result = a - b
    print(f"The difference between {a} and {b} is {result}")


def multiply(a, b):
    result = a * b
    print(f"The product of {a} and {b} is {result}")


def power(a, b):
    result = a**b
    print(f"{a} to the power of {b} is {result}")
